// Wardrobe art, drawn on the lion's 44 x 44 canvas so each item lands on the right part of its body.
import { arms, frame, layer, ol, part, paths, recolour, bbox, type Layer } from './sprites.ts';

type Art = { svg: string; icon?: string; box: { x: number; y: number; w: number; h: number } };
const art = (l: Layer): Art => ({ svg: paths(l), box: bbox(l) });

/** A top with sleeves: the sleeve is the lion's own arm, recoloured, so it follows the raised-arm frame too. */
function sleeved(l: Layer, cloth: string, shade: string): Art {
  const dress = (a: Layer) => recolour(a, { F: cloth, L: cloth, f: shade });
  return { svg: paths(l) + frame('sl-down', dress(arms.down)) + frame('sl-up', dress(arms.up), true), box: bbox(layer(l, arms.down)) };
}

/** The paw that closes over a held item. It belongs on the lion, so the item's wardrobe icon leaves it out. */
const grip = ol(part(27, 35, 'CCCf', '.cc.'));
const held = (l: Layer): Art => ({ svg: paths(layer(l, grip)), icon: paths(l), box: bbox(l) });

